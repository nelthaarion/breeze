package mcp

// tools_verify_test.go — the tests that prove the verification tools tell a
// working project apart from a broken one.
//
// The fixtures here are real Go modules that the real toolchain really compiles.
// A fixture that fed canned `go build` output to the parsers would test the
// regular expressions and nothing else, and the regular expressions are not the
// part that is likely to be wrong — the part that is likely to be wrong is the
// assumption about what the toolchain prints. So every test below runs `go`.
//
// The modules are deliberately dependency-free rather than generated by
// `breeze new`. A scaffolded project needs the breeze module resolved over the
// network to compile, so on an offline machine `go build` would fail for a reason
// that has nothing to do with the project's own correctness, and a test asserting
// "a good project verifies clean" would fail everywhere except on a warm cache.
// What these tools actually promise is to report the toolchain's findings
// faithfully, and a two-package module exercises that completely.

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// goodModule is a module that compiles, vets clean, passes its tests, and has
// one allocation-free benchmark and one that allocates.
//
// The two benchmarks exist so the allocation reporting can be checked in both
// directions: a tool that reported every benchmark as zero-allocation would pass
// a test that only had the first one.
var goodModule = map[string]string{
	"go.mod": "module example.com/verifyme\n\ngo 1.24\n",

	"calc/calc.go": `package calc

// Add returns the sum of two integers.
func Add(a, b int) int { return a + b }

// Join concatenates two strings, which allocates.
func Join(a, b string) string { return a + b }
`,

	"calc/calc_test.go": `package calc

import "testing"

var (
	intSink    int
	stringSink string
)

func TestAdd(t *testing.T) {
	if got := Add(2, 3); got != 5 {
		t.Errorf("Add(2,3) = %d, want 5", got)
	}
}

func BenchmarkAddIsAllocationFree(b *testing.B) {
	for i := 0; i < b.N; i++ {
		intSink = Add(i, 1)
	}
}

func BenchmarkJoinAllocates(b *testing.B) {
	left, right := "left", "right"
	for i := 0; i < b.N; i++ {
		stringSink = Join(left, right)
	}
}
`,

	// A second package with no test file at all, so the coverage tool has an
	// untested package to report. This is the case where a percentage would be
	// misleading rather than merely low.
	"untested/untested.go": `package untested

// Unused is never called by any test.
func Unused() string { return "nothing exercises this" }
`,
}

// newToolchainFixture writes a module and returns its root.
func newToolchainFixture(t *testing.T, files map[string]string) string {
	t.Helper()

	root := t.TempDir()
	for name, content := range files {
		path := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatalf("creating %s: %v", filepath.Dir(name), err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatalf("writing %s: %v", name, err)
		}
	}
	return root
}

// withFile returns a copy of a file set with one entry replaced or added. This
// keeps each broken variant a one-line difference from the working one, so a test
// failure points at the change rather than at a whole separate fixture.
func withFile(base map[string]string, name, content string) map[string]string {
	out := make(map[string]string, len(base)+1)
	for k, v := range base {
		out[k] = v
	}
	out[name] = content
	return out
}

// structOf pulls the structured payload out of a tool result.
//
// The result has been through the JSON-RPC encoder by the time a test sees it, so
// the payload is a map rather than the report struct. Reading it as a map is
// deliberate: it checks the JSON field names an agent will actually receive,
// which asserting against the Go struct would not.
func structOf(t *testing.T, result toolCallResult) map[string]any {
	t.Helper()

	shape, ok := result.StructuredContent.(map[string]any)
	if !ok {
		t.Fatalf("structured content is %T, not an object: %#v",
			result.StructuredContent, result.StructuredContent)
	}
	return shape
}

// stepsByName indexes a verification report's steps.
func stepsByName(t *testing.T, report map[string]any) map[string]map[string]any {
	t.Helper()

	raw, ok := report["steps"].([]any)
	if !ok {
		t.Fatalf("steps is %T, not a list", report["steps"])
	}

	out := make(map[string]map[string]any, len(raw))
	for _, entry := range raw {
		step, ok := entry.(map[string]any)
		if !ok {
			t.Fatalf("a step is %T, not an object", entry)
		}
		name, _ := step["name"].(string)
		out[name] = step
	}
	return out
}

// listOf reads a list-valued field as objects.
func listOf(t *testing.T, node map[string]any, key string) []map[string]any {
	t.Helper()

	raw, ok := node[key].([]any)
	if !ok {
		return nil
	}
	out := make([]map[string]any, 0, len(raw))
	for _, entry := range raw {
		obj, ok := entry.(map[string]any)
		if !ok {
			t.Fatalf("%s contains a %T, not an object", key, entry)
		}
		out = append(out, obj)
	}
	return out
}

// notesOf reads a notes list as one searchable string.
func notesOf(node map[string]any) string {
	raw, ok := node["notes"].([]any)
	if !ok {
		return ""
	}
	parts := make([]string, 0, len(raw))
	for _, entry := range raw {
		if text, ok := entry.(string); ok {
			parts = append(parts, text)
		}
	}
	return strings.Join(parts, " | ")
}

